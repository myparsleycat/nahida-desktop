// Imports per-character toon shading data into internal/ui/assets/character_toon, keyed by the character catalog's
// ids. Only the values and textures the model viewer's toon shaders read are kept.
//
// The Genshin, Star Rail and Zenless data comes from a file extracted from skowt.cc's 3D viewer:
// {characters: {"<game>/<catalog id>": {materials, images}}}, where each material carries the
// game material's floats, colors and texture names and images holds base64 WebP files by game texture name.
//
// The Endfield data comes from a file extracted from studio.warfarin.wiki:
// {characters: {"<chr_ id>": {materials: [null | {name, kind, diffuseRamp}], meshes: [{primitives: [{material,
// indices}]}]}}, images: {<name>: {mime, data}}}. Its material properties are obfuscated, so only the diffuse ramps
// and the index counts of the stock meshes are kept.
//
// Usage: node scripts/import-character-toon.mjs <skowt.json> <warfarin.json>

import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const OUTPUT = path.join(process.cwd(), 'internal/ui/assets/character_toon');
const EFMI_CATALOG = path.join(process.cwd(), 'internal/mod/character/data/efmi.json');

const NOTICE = `These textures and material values are game data: Genshin Impact, Honkai: Star Rail and Zenless Zone Zero
(c) HoYoverse; Arknights: Endfield (c) Hypergryph / GRYPHLINE.

Source of gimi, srmi and zzmi: the 3D viewer of https://skowt.cc
Source of efmi: https://studio.warfarin.wiki

They are generated by scripts/import-character-toon.mjs.
`;

// skowt names both Trailblazers and both March 7th forms alike; the extractor numbers them in its listing order.
const ALIASES = {
  'srmi/trailblazer#0': 'srmi/stelle',
  'srmi/trailblazer#1': 'srmi/caelus',
  'srmi/march-7th#0': 'srmi/march-7th',
  'srmi/march-7th#1': 'srmi/march-7th-the-hunt',
};

const GAMES = {
  gimi: {
    game: 'GIMI',
    role: /_Mat_([A-Za-z]+\d*)$/,
    floats:
      /^_(LightArea|UseMaterial[2-5]|Shininess[2-5]?|SpecMulti[2-5]?|OutLineIntensity[2-5]?|MetalMaterial|MTMapBrightness|MTShininess|MTSpecularScale|MTSpecularAttenInShadow)$/,
    colors:
      /^_(OutlineColor[2-5]?|SpecularColor[2-5]?|MTMapDarkColor|MTMapLightColor|MTShadowMultiColor|MTSpecularColor)$/,
    textures: /^_PackedShadowRampTex$/,
  },
  srmi: {
    game: 'SRMI',
    role: /_Mat_([A-Za-z0-9_]+)$|_(Body|Face|Hair)_Color/,
    floats: /^_(UseMaterialValuesLUT|SpecularIntensity\d|SpecularRoughness\d|SpecularShininess\d)$/,
    colors: /^_(OutlineColor\d?|RimColor\d|SpecularColor\d)$/,
    // HoyoToon blends the cool ramp in with a weight of 0.
    textures: /^_(DiffuseRampMultiTex|MaterialValuesPackLUT)$/,
  },
  zzmi: {
    game: 'ZZMI',
    role: /^MAT_[A-Za-z0-9]+_([A-Za-z0-9_]+)$/,
    floats: /^_(SpecIntensity|ToonSpecular\d?|Metallic|Glossiness)$/,
    colors: /^_(ShadowColor\d?|ShallowColor\d?|SpecularColor\d?|OutlineColor\d?)$/,
    textures: /^$/,
  },
};

function pick(record, pattern) {
  const kept = {};
  for (const [key, value] of Object.entries(record ?? {})) {
    if (pattern.test(key)) {
      kept[key] = value;
    }
  }
  return kept;
}

function sorted(characters) {
  return Object.fromEntries(Object.entries(characters).sort(([a], [b]) => a.localeCompare(b)));
}

async function writeGame(file, game, characters, images) {
  const dir = path.join(OUTPUT, file);
  await mkdir(dir, { recursive: true });
  for (const [name, image] of images) {
    if (image.mime !== 'image/webp') {
      throw new Error(`${file} ${name}: ${image.mime}`);
    }
    await writeFile(path.join(dir, `${name}.webp`), Buffer.from(image.data, 'base64'));
  }
  const output = sorted(characters);
  await writeFile(path.join(OUTPUT, `${file}.json`), `${JSON.stringify({ game, characters: output })}\n`);
  console.log(`${file}: ${Object.keys(output).length} characters, ${images.size} images`);
}

function importSkowt(extracted, file, spec) {
  const characters = {};
  const images = new Map();
  for (const [key, entry] of Object.entries(extracted.characters)) {
    const [game, id] = (ALIASES[key] ?? key).split('/');
    if (id.includes('#')) {
      throw new Error(`${key}: ambiguous entry without an alias`);
    }
    if (game !== file) {
      continue;
    }
    const used = new Set();
    const materials = [];
    for (const material of entry.materials) {
      const values = material.game;
      const match = spec.role.exec(material.name);
      const role = (match?.[1] ?? match?.[2])?.toLowerCase();
      if (!values || !role) {
        continue;
      }
      const textures = pick(values.textures, spec.textures);
      for (const name of Object.values(textures)) {
        used.add(name);
      }
      materials.push({
        role,
        floats: pick(values.floats, spec.floats),
        colors: pick(values.colors, spec.colors),
        textures,
      });
    }
    for (const name of used) {
      const image = entry.images?.[name];
      if (!image) {
        throw new Error(`${key}: texture ${name} has no image`);
      }
      images.set(name, image);
    }
    if (materials.length === 0) {
      console.warn(`${key}: skipped, no game material data`);
      continue;
    }
    characters[id] = { materials };
  }
  return { characters, images };
}

// Endfield's skin materials are body_* and face_*; the eyes and the overlay shadows are left out, as the viewer
// shades them without a ramp.
function efmiRole(material) {
  switch (material.kind) {
    case 'skin':
      return /_face_\d+$/.test(material.name) ? 'face' : 'body';
    case 'hair':
    case 'cloth':
      return material.kind;
    default:
      return '';
  }
}

function importWarfarin(extracted, catalog) {
  const ids = new Map(catalog.characters.map((entry) => [entry.key, entry.id]));
  const characters = {};
  const images = new Map();
  for (const [key, entry] of Object.entries(extracted.characters)) {
    const id = ids.get(key);
    if (!id) {
      throw new Error(`${key}: not in the EFMI character catalog`);
    }
    const indices = new Map();
    for (const mesh of entry.meshes) {
      for (const primitive of mesh.primitives) {
        indices.set(primitive.material, [...(indices.get(primitive.material) ?? []), primitive.indices]);
      }
    }
    const materials = [];
    entry.materials.forEach((material, index) => {
      const role = material && efmiRole(material);
      // A few materials of other shaders hold a specular ramp in the slot the extractor read.
      if (!role || !/_RD$/.test(material.diffuseRamp ?? '')) {
        return;
      }
      const image = extracted.images[material.diffuseRamp];
      if (!image) {
        throw new Error(`${key}: ramp ${material.diffuseRamp} has no image`);
      }
      images.set(material.diffuseRamp, image);
      materials.push({ role, indices: indices.get(index) ?? [], textures: { _RD: material.diffuseRamp } });
    });
    characters[id] = { materials };
  }
  return { characters, images };
}

const [skowtSource, warfarinSource] = process.argv.slice(2);
if (!skowtSource || !warfarinSource) {
  throw new Error('usage: node scripts/import-character-toon.mjs <skowt.json> <warfarin.json>');
}
const skowt = JSON.parse(await readFile(skowtSource, 'utf8'));
const warfarin = JSON.parse(await readFile(warfarinSource, 'utf8'));
const efmiCatalog = JSON.parse(await readFile(EFMI_CATALOG, 'utf8'));

await rm(OUTPUT, { recursive: true, force: true });
await mkdir(OUTPUT, { recursive: true });
await writeFile(path.join(OUTPUT, 'NOTICE.txt'), NOTICE);
for (const [file, spec] of Object.entries(GAMES)) {
  const { characters, images } = importSkowt(skowt, file, spec);
  await writeGame(file, spec.game, characters, images);
}
const efmi = importWarfarin(warfarin, efmiCatalog);
await writeGame('efmi', 'EFMI', efmi.characters, efmi.images);

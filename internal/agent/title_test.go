func insertTitleSession(t *testing.T, client *db.Client, title string) string {
	t.Helper()
	row := db.AgentSessionRow{ID: "session", ScopeType: "global", Title: title, CreatedAt: "1", UpdatedAt: "1"}
	if err := client.AgentSessions.Insert(t.Context(), row); err != nil {
		t.Fatal(err)
	}
	return row.ID
}

// writeAssistantText answers a streaming chat completions request with one text delta.
func writeAssistantText(response http.ResponseWriter, text string) {
	escaped := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`, "\r", "").Replace(text)
	response.Header().Set("Content-Type", "text/event-stream")
	_, _ = fmt.Fprintf(
		response,
		"data: {\"choices\":[{\"delta\":{\"content\":\"%s\"}}]}\n\ndata: [DONE]\n\n",
		escaped,
	)
}

func isTitleRequest(body map[string]any) bool {
	messages, _ := body["messages"].([]any)
	if len(messages) == 0 {
		return false
	}
	system, _ := messages[0].(map[string]any)
	return system["content"] == sessionTitlePrompt
}

func nextTitleRequest(t *testing.T, requests <-chan map[string]any) map[string]any {
	t.Helper()
	select {
	case body := <-requests:
		return body
	case <-time.After(5 * time.Second):
		t.Fatal("provider request was not received")
		return nil
	}
}

func waitForSessionTitle(t *testing.T, client *db.Client, sessionID, want string) {
	t.Helper()
	ctx := t.Context()
	deadline := time.Now().Add(10 * time.Second)
	stored := ""
	for time.Now().Before(deadline) {
		row, err := client.AgentSessions.Get(ctx, sessionID)
		if err != nil {
			t.Fatal(err)
		}
		if row != nil {
			stored = row.Title
			if stored == want {
				return
			}
		}
		time.Sleep(10 * time.Millisecond)
	}
	t.Fatalf("session title = %q, want %q", stored, want)
}

// titleEventSink captures the session-title stream events of one service.
type titleEventSink struct {
	events chan AgentStreamEvent
}

func newTitleEventSink() *titleEventSink {
	return &titleEventSink{events: make(chan AgentStreamEvent, 8)}
}

func (s *titleEventSink) emit(name string, payload ...any) {
	if name != "agent:update" || len(payload) != 1 {
		return
	}
	event, ok := payload[0].(AgentStreamEvent)
	if !ok || event.Type != "session-title" {
		return
	}
	select {
	case s.events <- event:
	default:
	}
}

func (s *titleEventSink) wait(t *testing.T) AgentStreamEvent {
	t.Helper()
	select {
	case event := <-s.events:
		return event
	case <-time.After(5 * time.Second):
		t.Fatal("no session-title event was emitted")
		return AgentStreamEvent{}
	}
}

func (s *titleEventSink) empty(t *testing.T) {
	t.Helper()
	select {
	case event := <-s.events:
		t.Fatalf("unexpected session-title event: %#v", event)
	case <-time.After(50 * time.Millisecond):
	}
}

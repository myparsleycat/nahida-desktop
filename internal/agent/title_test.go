func TestNormalizeSessionTitle(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name string
		raw  string
		want string
	}{
		{name: "plain", raw: "Broken mod textures", want: "Broken mod textures"},
		{
			name: "reasoning block",
			raw:  "<think>weighing options</think>\nBroken mod textures",
			want: "Broken mod textures",
		},
		{
			name: "unterminated reasoning block",
			raw:  "Broken mod textures\n<think>never closed",
			want: "Broken mod textures",
		},
		{name: "quoted", raw: `"Broken mod textures"`, want: "Broken mod textures"},
		{name: "bold", raw: "**Broken mod textures**", want: "Broken mod textures"},
		{name: "heading", raw: "## Broken mod textures", want: "Broken mod textures"},
		{name: "labelled", raw: "Title: Broken mod textures", want: "Broken mod textures"},
		{name: "first filled line", raw: "\n\nBroken mod textures\nGenerated by a model", want: "Broken mod textures"},
		{name: "collapsed whitespace", raw: "Broken   mod\ttextures", want: "Broken mod textures"},
		{name: "empty", raw: " \n\t ", want: ""},
		{name: "truncated", raw: strings.Repeat("a", 60), want: strings.Repeat("a", sessionTitleRunes) + "…"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			t.Parallel()
			if got := normalizeSessionTitle(test.raw); got != test.want {
				t.Fatalf("normalizeSessionTitle(%q) = %q, want %q", test.raw, got, test.want)
			}
		})
	}
}

func TestSessionTitleRequestSummarizesTheRequest(t *testing.T) {
	t.Parallel()
	ctx := t.Context()
	requests := make(chan map[string]any, 1)
	server := httptest.NewServer(http.HandlerFunc(func(response http.ResponseWriter, request *http.Request) {
		var body map[string]any
		if err := json.NewDecoder(request.Body).Decode(&body); err != nil {
			t.Errorf("decode provider request: %v", err)
			return
		}
		requests <- body
		writeAssistantText(response, "<think>weighing options</think>\nBroken mod textures")
	}))
	defer server.Close()

	sink := newTitleEventSink()
	service := newSettingsService(t, Options{HTTP: server.Client(), EventEmit: sink.emit})
	client, err := service.dbClient()
	if err != nil {
		t.Fatal(err)
	}
	question := "이 모드 텍스처가 깨져 보여. 원인을 찾아줘."
	fallback := messageTitle(question, nil)
	sessionID := insertTitleSession(t, client, fallback)

	service.summarizeSessionTitle(ctx, newTitleAdapter(server), sessionID, "run", fallback, question)

	body := nextTitleRequest(t, requests)
	if body["reasoning_effort"] != "low" {
		t.Fatalf("reasoning_effort = %#v", body["reasoning_effort"])
	}
	if tools, _ := body["tools"].([]any); len(tools) != 0 {
		t.Fatalf("title request carried tools: %#v", tools)
	}
	messages, _ := body["messages"].([]any)
	if len(messages) != 2 {
		t.Fatalf("title request messages = %#v", messages)
	}
	if system := messages[0].(map[string]any); system["content"] != sessionTitlePrompt {
		t.Fatalf("system prompt = %#v", system["content"])
	}
	if prompt, _ := messages[1].(map[string]any)["content"].(string); !strings.Contains(prompt, question) {
		t.Fatalf("user prompt = %q", prompt)
	}

	row, err := client.AgentSessions.Get(ctx, sessionID)
	if err != nil || row.Title != "Broken mod textures" {
		t.Fatalf("stored title = %#v, %v", row, err)
	}
	event := sink.wait(t)
	payload, _ := event.Payload.(map[string]any)
	if event.SessionID != sessionID || payload["title"] != "Broken mod textures" {
		t.Fatalf("session-title event = %#v", event)
	}
}

func TestSessionTitleRetriesWithoutReasoningEffort(t *testing.T) {
	t.Parallel()
	ctx := t.Context()
	requests := make(chan map[string]any, 2)
	server := httptest.NewServer(http.HandlerFunc(func(response http.ResponseWriter, request *http.Request) {
		var body map[string]any
		if err := json.NewDecoder(request.Body).Decode(&body); err != nil {
			t.Errorf("decode provider request: %v", err)
			return
		}
		requests <- body
		if _, present := body["reasoning_effort"]; present {
			response.WriteHeader(http.StatusBadRequest)
			_, _ = response.Write([]byte(`{"error":{"message":"unknown field reasoning_effort"}}`))
			return
		}
		writeAssistantText(response, "Broken mod textures")
	}))
	defer server.Close()

	service := newSettingsService(t, Options{HTTP: server.Client()})
	client, err := service.dbClient()
	if err != nil {
		t.Fatal(err)
	}
	sessionID := insertTitleSession(t, client, "first message")
	service.summarizeSessionTitle(
		ctx,
		newTitleAdapter(server),
		sessionID,
		"run",
		"first message",
		"why are my textures broken",
	)

	first := nextTitleRequest(t, requests)
	if first["reasoning_effort"] != "low" {
		t.Fatalf("first attempt reasoning_effort = %#v", first["reasoning_effort"])
	}
	second := nextTitleRequest(t, requests)
	if _, present := second["reasoning_effort"]; present {
		t.Fatalf("retry kept reasoning_effort: %#v", second)
	}
	row, err := client.AgentSessions.Get(ctx, sessionID)
	if err != nil || row.Title != "Broken mod textures" {
		t.Fatalf("stored title = %#v, %v", row, err)
	}
}


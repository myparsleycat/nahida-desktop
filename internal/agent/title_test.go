func TestSendGeneratesASessionSummaryTitle(t *testing.T) {
	t.Parallel()
	ctx := t.Context()
	server := httptest.NewServer(http.HandlerFunc(func(response http.ResponseWriter, request *http.Request) {
		var body map[string]any
		if err := json.NewDecoder(request.Body).Decode(&body); err != nil {
			t.Errorf("decode provider request: %v", err)
			return
		}
		if isTitleRequest(body) {
			writeAssistantText(response, "Broken mod texture diagnosis")
			return
		}
		writeAssistantText(response, "Looking into it.")
	}))
	defer server.Close()

	sink := newTitleEventSink()
	service, _ := newImageSessionService(t, Options{HTTP: server.Client(), EventEmit: sink.emit})
	input := headerSettingsInput(nil)
	input.Endpoint = server.URL
	if _, err := service.UpdateSettings(ctx, input); err != nil {
		t.Fatal(err)
	}
	session, err := service.CreateSession(ctx, AgentScope{Type: "global"})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := service.Send(ctx, session.ID, "이 모드 텍스처가 깨져 보여. 원인을 찾아줘.", nil); err != nil {
		t.Fatal(err)
	}
	client, err := service.dbClient()
	if err != nil {
		t.Fatal(err)
	}

	waitForSessionTitle(t, client, session.ID, "Broken mod texture diagnosis")
	if event := sink.wait(t); event.SessionID != session.ID {
		t.Fatalf("session-title event = %#v", event)
	}
}

